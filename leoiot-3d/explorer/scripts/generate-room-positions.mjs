#!/usr/bin/env node
// Dev tool (not part of the production build): reads each room's real-world
// (x, z) centre and this floor's walking height from the building models
// (model3d/room-navigation), for the legacy-style corridor navigation in
// src/nav/route.ts to snap a route onto a room's door.
//
// Run with: node scripts/generate-room-positions.mjs
// Re-run whenever a building model under models/*.gltf changes.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadGltf } from './gltf-reader.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const MODELS = join(__dirname, '../models');
const OUT = join(__dirname, '../src/nav/room-positions.generated.ts');

const FLOORS = {
  U: { file: 'ModelU.gltf', room: 'U' },
  E: { file: 'ModelE.gltf', room: 'E' },
  '1': { file: 'Model1F.gltf', room: '1' },
  '2': { file: 'Model2F.gltf', room: '2' },
  T: { file: 'ModelT.gltf', room: 'T' },
};

const positions = {};
const floorY = {};
for (const [floor, { file, room }] of Object.entries(FLOORS)) {
  const g = loadGltf(join(MODELS, file));
  const roomNames = [...g.nodesByName.keys()].filter((n) => n.startsWith(room) && !n.includes('-'));
  const centres = [];
  for (const name of roomNames) {
    const [idx] = g.nodesByName.get(name);
    const b = g.nodeBoundsXZ(idx);
    positions[name] = { floor, x: (b.minX + b.maxX) / 2, z: (b.minZ + b.maxZ) / 2 };
    centres.push((b.minY + b.maxY) / 2);
  }
  centres.sort((a, b) => a - b);
  floorY[floor] = centres[Math.floor(centres.length / 2)]; // median, robust to an outlier like a double-height atrium
  console.log(`floor ${floor}: ${roomNames.length} rooms, floorY ${floorY[floor].toFixed(3)}`);
}

let ts = `// GENERATED by scripts/generate-room-positions.mjs — do not edit by hand.
// Re-run that script after any building model under models/*.gltf changes.
import type { FloorId } from '../core/rooms';

export interface RoomPosition {
  floor: FloorId;
  x: number;
  z: number;
}

export const ROOM_POSITIONS: Record<string, RoomPosition> = ${JSON.stringify(positions, null, 2)};

export const FLOOR_Y: Record<FloorId, number> = ${JSON.stringify(floorY, null, 2)};
`;

writeFileSync(OUT, ts);
console.log('wrote', OUT);
